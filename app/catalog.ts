import { sample, w, type Sheet } from './sample';

export type BuiltinId = 'lion' | 'jellyfish';
export function builtinSheet(id: BuiltinId, level: string): Sheet {
  if (id === 'lion') return {...sample(level, '適中'), builtinId: id, cover: '/lion-cover.png'};
  const young = level === '幼兒園';
  const q = (prompt: string, options: string[], answer: number, explanation: string) => ({prompt:w(prompt), options:options.map(w), answer, explanation:w(explanation)});
  const mind = (label: string, prompt: string, answer: string) => ({label:w(label),prompt:w(prompt),answer:w(answer)});
  const open = (prompt: string, guide: string) => ({prompt:w(prompt),guide:w(guide)});
  return {
    sample:true, builtinId:id, cover:'/jellyfish-cover.png',
    title:'不說話的水母', source:'康軒學前8月份', level, difficulty:'適中',
    tags:['故事','海洋保護','辨識垃圾'], article:'',
    adapted:w(young
      ? '亮亮是一隻小水母。\n\n他看到一個像水母的東西，想和它做朋友。它不說話，只會隨著海水漂。\n\n它罩住海馬，又纏住螃蟹。海龜差一點把它吃下去。\n\n人們用撈網把它撈走。亮亮才知道，它是塑膠袋！\n\n亮亮提醒朋友：不要吃，也不要靠近。大家不亂丟垃圾，海洋才能乾乾淨淨。'
      : '小水母亮亮在珊瑚旁遇見一個新朋友。它有圓圓的身體，卻不會說話，也不會發光，只隨海流漂動。亮亮沒有仔細分辨，就把它當成水母。\n\n玩捉迷藏時，新朋友罩住了海馬，又纏住螃蟹。亮亮以為它不懂遊戲，所以替它道歉。海龜游來時，亮亮擔心新朋友被吃掉，連忙提醒它。\n\n一張撈網把新朋友撈上船。亮亮聽見人們說，那是亂丟的塑膠袋！他回想剛才的事，終於明白：新朋友不說話、不會發光，也感覺不到別人，因為它根本不是動物。\n\n亮亮發現，塑膠垃圾會纏住動物，也可能被當成食物。他開始提醒海洋朋友遠離假水母。亮亮更希望人們不亂丟垃圾，讓海洋生物安心生活。'),
    questions:young ? [
      q('亮亮是什麼動物？',['海馬','水母','海龜'],1,'亮亮是一隻小水母。'),
      q('新朋友會說話嗎？',['不會','會唱歌','會說你好'],0,'新朋友沒有說話，只發出刷拉的聲音。'),
      q('海馬被什麼罩住了？',['貝殼','海草','塑膠袋'],2,'亮亮以為是新水母的東西，其實是塑膠袋。'),
      q('誰用撈網把塑膠袋撈走？',['海龜','人們','亮亮'],1,'船上的人們用撈網把塑膠袋撈走。'),
      q('看到海裡的塑膠袋，應該怎麼做？',['不要吃，也不要靠近','把它當食物','拉著它玩'],0,'亮亮提醒朋友，塑膠袋不能吃，也不要靠近。')
    ] : [
      q('亮亮一開始為什麼把塑膠袋當成水母？',['因為它會發藍光','因為它說自己是水母','因為外形很像水母'],2,'它有圓圓的身體和像觸手的部分，讓亮亮誤認。'),
      q('哪個線索能幫亮亮發現新朋友不是動物？',['它不說話，也感覺不到碰撞','它住在海裡','它比亮亮大'],0,'不說話、不發光，勾到珊瑚和纏住動物都沒反應，是故事中的線索。'),
      q('亮亮替新朋友道歉時，還沒有知道什麼？',['海馬喜歡玩捉迷藏','新朋友其實是塑膠袋','海龜會游泳'],1,'他以為新朋友不懂遊戲，還不知道它不是動物。'),
      q('塑膠袋為什麼會讓海龜遇到危險？',['塑膠袋會追趕海龜','海龜害怕刷拉聲','海龜可能把它當水母吃下去'],2,'塑膠袋看起來像水母，可能被海龜當成食物。'),
      q('亮亮更希望人們不亂丟垃圾，原因是什麼？',['這樣能減少海洋動物遇到危險','這樣海馬不用玩遊戲','這樣海洋裡沒有水母'],0,'減少垃圾進入海洋，能讓動物少受纏繞與誤食的威脅。')
    ],
    mindTitle:w('不說話的水母'),
    mindInstruction:w(young?'用答案卡把故事連起來。':'整理亮亮從誤會到發現真相的過程。'),
    mind:young ? [
      mind('主角','誰想交新朋友？','小水母亮亮'),
      mind('發現','新朋友其實是什麼？','塑膠袋'),
      mind('危險','海馬怎麼了？','被罩住'),
      mind('保護','怎樣讓海洋乾淨？','不亂丟垃圾')
    ] : [
      mind('誤會','亮亮把什麼當成新朋友？','把塑膠袋當成水母'),
      mind('線索','新朋友有什麼不尋常的表現？','不說話、不發光、碰到別人沒反應'),
      mind('危險','塑膠垃圾會怎樣傷害動物？','纏住動物，也可能被誤食'),
      mind('行動','亮亮和人們可以分別做什麼？','亮亮提醒朋友遠離；人們不亂丟垃圾')
    ],
    open:young ? [
      open('你想對亮亮說什麼？','可以說說亮亮提醒朋友的做法，或謝謝他。'),
      open('去海邊玩，垃圾要放哪裡？','引導孩子說出帶走垃圾、放進適當垃圾桶；遇到不認識的垃圾請找大人。')
    ] : [
      open('如果你是亮亮，在牽起新朋友之前會先觀察什麼？請說說理由。','鼓勵從故事找出線索，如是否會動、回應、有無生命跡象；外形相似不代表是同一種東西。'),
      open('有人說：「把海裡的垃圾撈走就好了。」你同意嗎？還可以怎麼做？','可以同意清理有幫助，再說明減少使用一次性塑膠、不亂丟和帶走垃圾能減少新的垃圾；開放不同理由。')
    ]
  };
}
export const builtinLibrary = (level: string) => (['jellyfish','lion'] as BuiltinId[]).map(id => builtinSheet(id,level));
